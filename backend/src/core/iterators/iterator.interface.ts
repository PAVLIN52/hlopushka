/**
 * Общий интерфейс итератора (принцип VI конституции, паттерн «Итератор»).
 *
 * Контракт:
 * - `next()` на пустой коллекции бросает `CustomException` с кодом `ITERATOR_EMPTY`;
 * - `next()` после конца коллекции бросает `CustomException` с кодом `ITERATOR_EXHAUSTED`;
 * - `[Symbol.iterator]` позволяет использовать итератор в `for...of`
 *   (обход начинается с текущей позиции).
 */
export interface IIterator<T> extends Iterable<T> {
  /** Есть ли ещё элементы. */
  hasNext(): boolean;

  /** Возвращает следующий элемент и сдвигает позицию. */
  next(): T;

  /** Возвращает итератор в начальное положение. */
  reset(): void;
}
